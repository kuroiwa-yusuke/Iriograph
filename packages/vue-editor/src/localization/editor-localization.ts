export type EditorTranslator = (
  key: EditorMessageKey,
  parameters?: EditorMessageParameters,
) => string;

export type EditorLocalization = {
  locale: Readonly<Ref<EditorLocale>>;
  semanticLocales: ComputedRef<readonly string[]>;
  t: EditorTranslator;
};

export const editorLocalizationKey: InjectionKey<EditorLocalization> = Symbol("iriograph-editor-localization");

export function isEditorLocale(value: unknown): value is EditorLocale {
  return typeof value === "string" && editorLocales.includes(value as EditorLocale);
}

export function translateEditorMessage(
  locale: EditorLocale,
  key: EditorMessageKey,
  parameters: EditorMessageParameters = {},
): string {
  const template = (locale === "ja" ? ja : en)[key];
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/gu, (match, name: string) => (
    Object.hasOwn(parameters, name) ? String(parameters[name]) : match
  ));
}

export function provideEditorLocalization(
  locale: Ref<EditorLocale>,
  semanticLocales: ComputedRef<readonly string[]>,
): EditorLocalization {
  const context: EditorLocalization = {
    locale: readonly(locale),
    semanticLocales,
    t: (key, parameters) => translateEditorMessage(locale.value, key, parameters),
  };
  provide(editorLocalizationKey, context);
  return context;
}

export function useEditorLocalization(): EditorLocalization {
  const injected = inject(editorLocalizationKey, undefined);
  if (injected) return injected;
  const locale = ref<EditorLocale>("en");
  return {
    locale: readonly(locale),
    semanticLocales: computed(() => [locale.value]),
    t: (key, parameters) => translateEditorMessage(locale.value, key, parameters),
  };
}

export function createStaticEditorLocalization(
  locale: EditorLocale,
  semanticLocales: readonly string[] = [locale],
): EditorLocalization {
  const localeRef = ref(locale);
  return {
    locale: readonly(localeRef),
    semanticLocales: computed(() => [...semanticLocales]),
    t: (key, parameters) => translateEditorMessage(localeRef.value, key, parameters),
  };
}

